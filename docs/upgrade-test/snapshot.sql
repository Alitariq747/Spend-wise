SELECT 'count', 'expense', COUNT(*) FROM ZEXPENSE;
SELECT 'count', 'card', COUNT(*) FROM ZCREDITCARD;
SELECT 'count', 'category', COUNT(*) FROM ZCATEGORYENTITY;
SELECT 'count', 'budget', COUNT(*) FROM ZBUDGET;
SELECT 'count', 'catbudget', COUNT(*) FROM ZCATEGORYMONTHLYBUDGET;
SELECT 'count', 'settings', COUNT(*) FROM ZSETTINGS;
SELECT 'sum', 'expense', SUM(ZAMOUNT) FROM ZEXPENSE;
SELECT 'exp', hex(e.ZID), e.ZDATE, e.ZAMOUNT, e.ZMERCHANT, e.ZMETHOD, e.ZMONTHKEY, c.ZNAME, k.ZNAME, k.ZCYCLELIMIT
  FROM ZEXPENSE e LEFT JOIN ZCATEGORYENTITY c ON c.Z_PK = e.ZCATEGORY LEFT JOIN ZCREDITCARD k ON k.Z_PK = e.ZCARD ORDER BY e.ZDATE;
SELECT 'card', Z_PK, ZNAME, ZCYCLELIMIT, ZSTATEMENTDAY, ZDUEDAY, ZCOLORRAW FROM ZCREDITCARD ORDER BY Z_PK;
SELECT 'cat', Z_PK, ZNAME, ZEMOJI, ZMONTHLYBUDGET, ZCOLORHEX, ZISSYSTEMOTHER FROM ZCATEGORYENTITY ORDER BY Z_PK;
SELECT 'budget', hex(ZID), ZMONTHKEY, ZAMOUNT FROM ZBUDGET ORDER BY ZMONTHKEY;
SELECT 'catbudget', b.ZMONTHKEY, b.ZAMOUNT, c.ZNAME FROM ZCATEGORYMONTHLYBUDGET b LEFT JOIN ZCATEGORYENTITY c ON c.Z_PK = b.ZCATEGORY ORDER BY b.ZMONTHKEY;
SELECT 'settings', ZCREATEDAT, ZONBOARDINGCOMPLETE, ZCURRENCYCODE, ZAPPEARANCERAW, ZREMINDERLEVELRAW, ZPROUNLOCKED, ZICLOUDSYNCON FROM ZSETTINGS;
